//! Generates the typed CDP domain modules in `crates/cdp/src/domains` from the
//! vendored `browser_protocol.json` and `js_protocol.json` (plan 01,
//! milestone 1.2).
//!
//! `cargo xtask gen-cdp [--check]` runs the `cdp-gen` binary, which calls
//! [`run`]. Inputs live in `crates/cdp/protocol/`:
//! - `browser_protocol.json`, `js_protocol.json`: the protocol;
//! - `domains.txt`: the allow-list of domains to generate;
//! - `PROTOCOL_VERSION`: the pinned Chromium revision.
//!
//! Per domain, the output has one struct per object type, one enum (with a
//! catch-all `Unknown` variant) per string enum, a `XParams`/`XReturns` pair
//! plus a `crate::Command` impl per command, and a struct plus a
//! `crate::Event` impl per event.

use std::collections::BTreeMap;
use std::fmt::{self, Write as _};
use std::fs;
use std::io::Write as _;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

mod emit;
mod schema;
mod select;

/// A generation failure, with a message meant for a developer.
#[derive(Debug)]
pub struct Error(String);

impl fmt::Display for Error {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

impl std::error::Error for Error {}

impl From<String> for Error {
    fn from(msg: String) -> Self {
        Error(msg)
    }
}

/// The generator's inputs, as file contents.
#[derive(Debug, Clone, Copy)]
pub struct Sources<'s> {
    pub browser_protocol: &'s str,
    pub js_protocol: &'s str,
    pub domains: &'s str,
    pub protocol_version: &'s str,
}

/// Generates every file of the `domains` module, keyed by file name
/// (`mod.rs`, `page.rs`, …). The code is not formatted yet; see [`rustfmt`].
pub fn generate(src: Sources<'_>) -> Result<BTreeMap<String, String>, Error> {
    let parse = |name: &str, json: &str| {
        serde_json::from_str::<schema::Protocol>(json).map_err(|e| Error(format!("{name}: {e}")))
    };
    let mut domains = parse("browser_protocol.json", src.browser_protocol)?.domains;
    domains.extend(parse("js_protocol.json", src.js_protocol)?.domains);
    let revision = parse_revision(src.protocol_version)?;
    let allowed = select::parse_allowlist(src.domains)?;

    let index = select::Index::new(&domains)?;
    let modules = select::select(&index, &allowed)?;
    let contains = emit::containment(&index)?;

    let mut files = BTreeMap::new();
    let mut mod_rs = format!(
        "//! Typed CDP domains, generated by `cargo xtask gen-cdp` from\n\
         //! `crates/cdp/protocol/`. Do not edit; change `domains.txt` or the\n\
         //! generator instead.\n\
         \n\
         // @generated by `cargo xtask gen-cdp`. Do not edit.\n\
         \n\
         #![allow(clippy::all, clippy::pedantic)]\n\
         #![allow(rustdoc::all)]\n\
         \n\
         /// The Chromium revision the protocol was taken from\n\
         /// (`crates/cdp/protocol/PROTOCOL_VERSION`).\n\
         pub const PROTOCOL_REVISION: u32 = {revision};\n\n"
    );
    for (name, module) in &modules {
        let file = emit::module_name(name);
        files.insert(
            format!("{file}.rs"),
            emit::module(&index, &contains, module)?,
        );
        let _ = writeln!(mod_rs, "pub mod {file};");
    }
    files.insert("mod.rs".to_owned(), mod_rs);
    Ok(files)
}

/// Reads `revision = N` from `PROTOCOL_VERSION`.
fn parse_revision(text: &str) -> Result<u32, Error> {
    text.lines()
        .filter_map(|l| l.split_once('='))
        .find(|(k, _)| k.trim() == "revision")
        .and_then(|(_, v)| v.trim().parse().ok())
        .ok_or_else(|| Error("PROTOCOL_VERSION has no `revision = <number>` line".into()))
}

/// Formats code with `rustfmt` (or `$RUSTFMT`) using the workspace's
/// `rustfmt.toml`, so the output passes `cargo fmt --check` as is.
pub fn rustfmt(code: &str, config: &Path) -> Result<String, Error> {
    let bin = std::env::var_os("RUSTFMT").unwrap_or_else(|| "rustfmt".into());
    let mut child = Command::new(bin)
        .arg("--edition=2024")
        .arg("--config-path")
        .arg(config)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .map_err(|e| Error(format!("run rustfmt: {e}")))?;
    let mut stdin = child
        .stdin
        .take()
        .ok_or_else(|| Error("rustfmt: no stdin".into()))?;
    let input = code.to_owned();
    // Write from another thread so a full stdout pipe cannot deadlock us.
    let writer = std::thread::spawn(move || stdin.write_all(input.as_bytes()));
    let out = child
        .wait_with_output()
        .map_err(|e| Error(format!("rustfmt: {e}")))?;
    writer
        .join()
        .map_err(|_| Error("rustfmt: writer thread panicked".into()))?
        .map_err(|e| Error(format!("rustfmt: write stdin: {e}")))?;
    if !out.status.success() {
        return Err(Error(format!(
            "rustfmt failed ({}):\n{}",
            out.status,
            String::from_utf8_lossy(&out.stderr)
        )));
    }
    String::from_utf8(out.stdout).map_err(|e| Error(format!("rustfmt: {e}")))
}

/// Where the inputs and outputs live, relative to the workspace root.
#[derive(Debug, Clone)]
pub struct Layout {
    pub protocol_dir: PathBuf,
    pub out_dir: PathBuf,
    pub rustfmt_toml: PathBuf,
}

impl Layout {
    pub fn new(workspace_root: &Path) -> Self {
        Layout {
            protocol_dir: workspace_root.join("crates/cdp/protocol"),
            out_dir: workspace_root.join("crates/cdp/src/domains"),
            rustfmt_toml: workspace_root.join("rustfmt.toml"),
        }
    }
}

/// Generates and formats every file, keyed by file name.
pub fn generate_formatted(layout: &Layout) -> Result<BTreeMap<String, String>, Error> {
    let read = |name: &str| {
        let path = layout.protocol_dir.join(name);
        fs::read_to_string(&path).map_err(|e| Error(format!("read {}: {e}", path.display())))
    };
    let (browser, js, domains, version) = (
        read("browser_protocol.json")?,
        read("js_protocol.json")?,
        read("domains.txt")?,
        read("PROTOCOL_VERSION")?,
    );
    let files = generate(Sources {
        browser_protocol: &browser,
        js_protocol: &js,
        domains: &domains,
        protocol_version: &version,
    })?;
    files
        .into_iter()
        .map(|(name, code)| {
            let formatted =
                rustfmt(&code, &layout.rustfmt_toml).map_err(|e| Error(format!("{name}: {e}")))?;
            Ok((name, formatted))
        })
        .collect()
}

/// Files whose committed contents differ from freshly generated ones.
#[derive(Debug, Default, PartialEq, Eq)]
pub struct Drift {
    pub changed: Vec<String>,
    pub missing: Vec<String>,
    /// `.rs` files in the output directory the generator no longer makes.
    pub stale: Vec<String>,
}

impl Drift {
    pub fn is_empty(&self) -> bool {
        self.changed.is_empty() && self.missing.is_empty() && self.stale.is_empty()
    }
}

impl fmt::Display for Drift {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        for (label, files) in [
            ("changed", &self.changed),
            ("missing", &self.missing),
            ("stale", &self.stale),
        ] {
            for file in files {
                writeln!(f, "  {label}: {file}")?;
            }
        }
        Ok(())
    }
}

/// Compares generated files with the output directory.
pub fn check(layout: &Layout, files: &BTreeMap<String, String>) -> Result<Drift, Error> {
    let mut drift = Drift::default();
    for (name, code) in files {
        match fs::read_to_string(layout.out_dir.join(name)) {
            Ok(existing) if existing == *code => {}
            Ok(_) => drift.changed.push(name.clone()),
            Err(_) => drift.missing.push(name.clone()),
        }
    }
    drift.stale = stale_files(layout, files)?;
    Ok(drift)
}

/// Writes the generated files and deletes stale ones.
pub fn write(layout: &Layout, files: &BTreeMap<String, String>) -> Result<(), Error> {
    let dir = &layout.out_dir;
    fs::create_dir_all(dir).map_err(|e| Error(format!("create {}: {e}", dir.display())))?;
    for name in stale_files(layout, files)? {
        let path = dir.join(&name);
        fs::remove_file(&path).map_err(|e| Error(format!("remove {}: {e}", path.display())))?;
    }
    for (name, code) in files {
        let path = dir.join(name);
        if fs::read_to_string(&path).is_ok_and(|old| old == *code) {
            continue;
        }
        fs::write(&path, code).map_err(|e| Error(format!("write {}: {e}", path.display())))?;
    }
    Ok(())
}

fn stale_files(layout: &Layout, files: &BTreeMap<String, String>) -> Result<Vec<String>, Error> {
    let dir = &layout.out_dir;
    let entries = match fs::read_dir(dir) {
        Ok(entries) => entries,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(Vec::new()),
        Err(e) => return Err(Error(format!("read {}: {e}", dir.display()))),
    };
    let mut stale = Vec::new();
    for entry in entries {
        let entry = entry.map_err(|e| Error(format!("read {}: {e}", dir.display())))?;
        let name = entry.file_name().to_string_lossy().into_owned();
        let is_rs = Path::new(&name).extension().is_some_and(|ext| ext == "rs");
        if is_rs && !files.contains_key(&name) {
            stale.push(name);
        }
    }
    stale.sort();
    Ok(stale)
}

