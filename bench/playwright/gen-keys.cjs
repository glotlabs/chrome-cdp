// Generates crates/engine/src/input/keys/table.rs from Playwright's
// (Apache-2.0) US keyboard layout and macOS editing commands, as bundled in
// the playwright-core this directory installs:
//
//   npm ci && node gen-keys.cjs > ../../crates/engine/src/input/keys/table.rs
//
// Editing commands that insert text are left out, and the trailing `:` of
// each is dropped, as Playwright does before sending them.
const fs = require('fs');
const path = require('path');
const pkg = require('playwright-core/package.json');
const src = fs.readFileSync(path.join(path.dirname(require.resolve('playwright-core/package.json')), 'lib/coreBundle.js'), 'utf8');
const start = src.indexOf('USKeyboardLayout = {');
const end = src.indexOf('};', start);
const layout = eval('(' + src.slice(start + 'USKeyboardLayout = '.length, end + 1) + ')');
const ms = src.indexOf('macEditingCommands = {');
const me = src.indexOf('};', ms);
const mac = eval('(' + src.slice(ms + 'macEditingCommands = '.length, me + 1) + ')');
const q = (s) => JSON.stringify(s).replace(/\\u0000/g, '\\0');
let out = `// Generated by bench/playwright/gen-keys.cjs from playwright-core ${pkg.version}
// (usKeyboardLayout.ts and macEditingCommands.ts; Apache-2.0, see NOTICE).
// Do not edit.

use super::KeyDef;

`;
out += '/// Every key of the US layout, by `code`.\n';
out += 'pub(super) const LAYOUT: &[KeyDef] = &[\n';
for (const [code, d] of Object.entries(layout)) {
  const opt = (v) => (v === undefined ? 'None' : `Some(${typeof v === 'string' ? q(v) : v})`);
  out += `    KeyDef { code: ${q(code)}, key: ${q(d.key)}, key_code: ${d.keyCode}, key_code_without_location: ${d.keyCodeWithoutLocation ?? d.keyCode}, shift_key: ${opt(d.shiftKey)}, shift_key_code: ${opt(d.shiftKeyCode)}, text: ${q(d.text ?? '')}, location: ${d.location ?? 0} },\n`;
}
out += '];\n\n';
out += '/// The editing commands a macOS browser runs for a shortcut\n/// (`Shift+Control+Alt+Meta+code`), which synthetic key events do not run there.\n';
out += 'pub(super) const MAC_EDITING_COMMANDS: &[(&str, &[&str])] = &[\n';
for (const [k, v] of Object.entries(mac)) {
  const list = (Array.isArray(v) ? v : [v]).filter((c) => !c.startsWith('insert')).map((c) => c.slice(0, -1));
  if (!list.length) continue;
  out += `    (${q(k)}, &[${list.map(q).join(', ')}]),\n`;
}
out += '];\n';
process.stdout.write(out);
